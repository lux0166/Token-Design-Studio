import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { request as httpRequest } from 'node:http';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { formatWorkflowGuide } from '../shared/workflow.js';

test('real HTTP and stdio MCP share disk-backed editor state; guards, locks, concurrency and export', { timeout: 30000 }, async t => {
  const dir = mkdtempSync(join(tmpdir(), 'token-studio-mcp-'));
  // Dedicated test process uses an isolated data file; never touches the user's workspace.
  const server = spawn(process.execPath, ['--import', 'tsx', 'server/index.ts'], { cwd: resolve('.'), env: { ...process.env, PORT: '14328', STUDIO_DATA_FILE: join(dir, 'studio.json') }, stdio: ['ignore', 'pipe', 'pipe'] });
  let errors = ''; server.stderr.on('data', d => { errors += String(d); });
  t.after(async () => { server.kill(); await new Promise<void>(done => { if (server.exitCode !== null) done(); else server.once('exit', () => done()); }); rmSync(dir, { recursive: true, force: true }); });
  await new Promise<void>((done, reject) => {
    const timer = setTimeout(() => reject(new Error(`Server timeout: ${errors}`)), 10000);
    server.stdout.on('data', d => { if (String(d).includes('Token Studio:')) { clearTimeout(timer); done(); } });
    server.once('exit', () => { clearTimeout(timer); reject(new Error(errors)); });
  });
  const base = 'http://127.0.0.1:14328';
  const client = new Client({ name: 'integration-test', version: '1.0.0' });
  await client.connect(new StreamableHTTPClientTransport(new URL(`${base}/mcp`)));
  t.after(() => client.close());
  const list = await client.listTools(); assert.equal(list.tools.length, 17);
  assert.ok(list.tools.some(tool => tool.name === 'get_workflow'));
  assert.ok(client.getInstructions()?.includes('get_workflow'));
  const call = async (name: string, args = {}) => {
    const result = await client.callTool({ name, arguments: args });
    return { error: result.isError, data: result.content && Array.isArray(result.content) && result.content[0]?.type === 'text' ? result.content[0].text as string : '' };
  };
  const systems = JSON.parse((await call('list_systems')).data); const id = systems.systems[0].id;
  const state = async () => (await fetch(`${base}/api/state`)).json();
  const beforeWorkflow = await state();
  const workflow = JSON.parse((await call('get_workflow', { mode: 'replicate' })).data);
  assert.equal(workflow.mode, 'replicate');
  assert.equal(workflow.phases.length, 7);
  assert.equal(workflow.version, '1.3.2');
  assert.ok(workflow.phases.some((phase: { id: string }) => phase.id === 'interview'));
  assert.match(workflow.interviewGuide, /SPEC.md/);
  assert.match(client.getInstructions() || '', /https:\/\/icones.js.org\//);
  assert.match(client.getInstructions() || '', /https:\/\/koboyo.com\/icons/);
  assert.equal(workflow.reuseGuide, readFileSync(resolve('skills/token-studio-shadcn/references/reuse.md'), 'utf8'));
  assert.match(workflow.reuseGuide, /https:\/\/icones.js.org\//);
  assert.match(workflow.reuseGuide, /https:\/\/koboyo.com\/icons\/license/);
  const reuseResource = await client.readResource({ uri: workflow.resources.reuse });
  assert.ok('text' in reuseResource.contents[0]);
  assert.equal(reuseResource.contents[0].text, workflow.reuseGuide);
  assert.equal(workflow.designQualityGuide, readFileSync(resolve('skills/token-studio-shadcn/references/design-quality.md'), 'utf8'));
  const qualityResource = await client.readResource({ uri: workflow.resources.designQuality });
  assert.ok('text' in qualityResource.contents[0]);
  assert.equal(qualityResource.contents[0].text, workflow.designQualityGuide);
  assert.ok(formatWorkflowGuide(workflow).includes(workflow.designQualityGuide));
  assert.equal((await state()).revision, beforeWorkflow.revision);
  assert.deepEqual((await state()).systems, beforeWorkflow.systems);
  const workflowResource = await client.readResource({ uri: 'token-studio://workflow' });
  const workflowContent = workflowResource.contents[0];
  assert.ok('text' in workflowContent);
  assert.equal(workflowContent.text, workflow.instructions);
  const promptList = await client.listPrompts();
  assert.ok(promptList.prompts.some(prompt => prompt.name === 'design_and_ship'));
  assert.ok(promptList.prompts.some(prompt => prompt.name === 'grill_me'));
  const interviewResource = await client.readResource({ uri: 'token-studio://workflow/interview' });
  const interviewContent = interviewResource.contents[0];
  assert.ok('text' in interviewContent);
  assert.equal(interviewContent.text, workflow.interviewGuide);
  const grillWorkflow = JSON.parse((await call('get_workflow', { mode: 'grill-me' })).data);
  assert.equal(grillWorkflow.mode, 'grill-me');
  const grillPrompt = await client.getPrompt({ name: 'grill_me', arguments: { task: 'Clarify a one-to-one learning platform.' } });
  assert.equal(grillPrompt.messages[0].content.type, 'text');
  if (grillPrompt.messages[0].content.type === 'text') {
    assert.ok(grillPrompt.messages[0].content.text.includes(grillWorkflow.modeInstructions));
    assert.ok(grillPrompt.messages[0].content.text.includes(workflow.interviewGuide));
    assert.ok(grillPrompt.messages[0].content.text.includes(workflow.designQualityGuide));
    assert.match(grillPrompt.messages[0].content.text, /Do not implement the product in this mode/);
  }
  assert.equal((await state()).revision, beforeWorkflow.revision);
  const task = 'Implement the supplied signup design in the existing project.';
  const prompt = await client.getPrompt({ name: 'design_and_ship', arguments: { task, mode: 'replicate' } });
  assert.equal(prompt.messages[0].content.type, 'text');
  if (prompt.messages[0].content.type === 'text') {
    assert.ok(prompt.messages[0].content.text.includes(task));
    assert.ok(prompt.messages[0].content.text.includes(workflow.modeInstructions));
    assert.ok(prompt.messages[0].content.text.includes(workflow.instructions));
    assert.ok(prompt.messages[0].content.text.includes(workflow.interviewGuide));
    assert.ok(prompt.messages[0].content.text.includes(workflow.designQualityGuide));
    assert.ok(prompt.messages[0].content.text.includes(workflow.reuseGuide));
  }
  assert.equal((await call('get_workflow', { mode: 'invalid-mode' })).error, true);
  await assert.rejects(() => client.getPrompt({ name: 'design_and_ship', arguments: { task, mode: 'invalid-mode' } }));
  const apiWorkflow = await fetch(`${base}/api/workflow?mode=replicate`);
  assert.deepEqual(await apiWorkflow.json(), workflow);
  assert.equal((await fetch(`${base}/api/workflow?mode=invalid-mode`)).status, 400);
  assert.deepEqual(await (await fetch(`${base}/api/workflow?mode=grill-me`)).json(), grillWorkflow);
  assert.equal((await fetch(`${base}/api/status`)).status, 200);
  const latest = JSON.parse((await call('get_system', { systemId: id })).data);
  const result = await call('update_tokens', { systemId: id, expectedRevision: latest.revision, patch: { light: { primary: '#2563EB' }, settings: { radius: 12 } } });
  assert.ok(!result.error, result.data); assert.equal((await state()).systems[0].light.primary, '#2563EB');
  const stale = await call('update_tokens', { systemId: id, expectedRevision: latest.revision, patch: { settings: { radius: 4 } } }); assert.equal(stale.error, true);
  const rev = (await state()).revision;
  const locked = await fetch(`${base}/api/systems/${id}/lock`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ path: 'light.primary', expectedRevision: rev }) }); assert.equal(locked.status, 200);
  const lockRead = JSON.parse((await call('get_system', { systemId: id })).data);
  const refused = await call('update_tokens', { systemId: id, expectedRevision: lockRead.revision, patch: { light: { primary: '#FFFFFF', foreground: '#ABCDEF' } } });
  assert.equal(refused.error, true); assert.match(refused.data, /đã khóa/); assert.equal((await state()).systems[0].light.foreground, '#0F172A');
  const contrast = await call('check_contrast', { systemId: id, mode: 'light' }); assert.equal(JSON.parse(contrast.data).pairs.length, 7);
  const css = await call('export_css', { systemId: id }); assert.match(JSON.parse(css.data).css, /--primary: #2563EB/);
  const preview = await call('import_css', { systemId: id, css: ':root { --radius: 1rem; }', apply: false }); assert.equal(JSON.parse(preview.data).applied, false); assert.equal((await state()).systems[0].settings.radius, 12);
  const apply = await call('import_css', { systemId: id, css: ':root { --radius: 1rem; }', apply: true, expectedRevision: (await state()).revision }); assert.ok(!apply.error, apply.data); assert.equal((await state()).systems[0].settings.radius, 16);
  const resources = await client.listResources(); assert.ok(resources.resources.some(resource => resource.uri === 'token-studio://workspace'));
  assert.equal(resources.resources.length, 9);
  const catalogList = JSON.parse((await call('list_themes', { query: 'cyber' })).data);
  assert.equal(catalogList.themes.length, 1);
  assert.equal(catalogList.themes[0].id, 'tweakcn:cyberpunk');
  const catalogTheme = JSON.parse((await call('get_theme', { themeId: 'tweakcn:cyberpunk' })).data);
  const createdThemeSystem = JSON.parse((await call('create_system', { name: 'Library integration', themeId: catalogTheme.id })).data);
  assert.equal(createdThemeSystem.name, 'Library integration');
  assert.deepEqual(createdThemeSystem.light, catalogTheme.snapshot.light);
  const libraryId = createdThemeSystem.id;
  for (const path of ['light.primary', 'settings.radius']) {
    assert.equal((await fetch(`${base}/api/systems/${libraryId}/lock`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ path, expectedRevision: (await state()).revision }) })).status, 200);
  }
  const libraryBefore = JSON.parse((await call('get_system', { systemId: libraryId })).data);
  const previewTheme = JSON.parse((await call('apply_theme', { systemId: libraryId, themeId: 'tweakcn:vercel' })).data);
  assert.equal(previewTheme.applied, false);
  assert.ok(previewTheme.changed > 1);
  assert.deepEqual(previewTheme.keptLockedPaths, ['light.primary', 'settings.radius']);
  assert.equal((await state()).revision, libraryBefore.revision);
  assert.equal((await call('apply_theme', { systemId: libraryId, themeId: 'tweakcn:vercel', apply: true })).error, true);
  const appliedTheme = JSON.parse((await call('apply_theme', { systemId: libraryId, themeId: 'tweakcn:vercel', apply: true, expectedRevision: libraryBefore.revision })).data);
  assert.equal(appliedTheme.system.light.primary, libraryBefore.system.light.primary);
  assert.equal(appliedTheme.system.settings.radius, libraryBefore.system.settings.radius);
  assert.equal(appliedTheme.system.name, libraryBefore.system.name);
  assert.equal(appliedTheme.system.history.length, libraryBefore.system.history.length + 1);
  assert.equal((await call('apply_theme', { systemId: libraryId, themeId: 'tweakcn:vercel', apply: true, expectedRevision: libraryBefore.revision })).error, true);
  assert.equal((await call('get_theme', { themeId: 'invalid-theme' })).error, true);
  const beforeInvalidTheme = (await state()).revision;
  const invalidThemeResponse = await fetch(`${base}/api/systems`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ name: 'Invalid theme', themeId: 'invalid-theme' }) });
  assert.equal(invalidThemeResponse.status, 400);
  assert.equal((await state()).revision, beforeInvalidTheme);
  const crossSite = await fetch(`${base}/api/state`, { headers: { Origin: 'https://untrusted.example' } }); assert.equal(crossSite.status, 403);
  // Node fetch rewrites Host; use node:http to exercise the actual hostile header.
  const badHost = await new Promise<number | undefined>((done, reject) => {
    const req = httpRequest(`${base}/api/state`, { headers: { Host: 'untrusted.example' } }, res => { res.resume(); done(res.statusCode); });
    req.on('error', reject); req.end();
  }); assert.equal(badHost, 403);
  const stateNow = await state(); assert.ok(stateNow.calls.some((c: any) => !c.ok)); assert.ok(stateNow.systems[0].history.some((h: any) => h.source === 'agent'));
  const stdio = new Client({ name: 'stdio-test', version: '1.0.0' });
  await stdio.connect(new StdioClientTransport({ command: process.execPath, args: ['--import', 'tsx', resolve('server/stdio.ts')], cwd: resolve('.'), env: { ...Object.fromEntries(Object.entries(process.env).filter((v): v is [string, string] => v[1] !== undefined)), STUDIO_MCP_URL: `${base}/mcp` } }));
  t.after(() => stdio.close());
  const stdioList = await stdio.listTools(); assert.equal(stdioList.tools.length, 17);
  assert.ok(stdio.getInstructions()?.includes('get_workflow'));
  const stdioPrompts = await stdio.listPrompts();
  assert.deepEqual(stdioPrompts.prompts, promptList.prompts);
  const stdioPrompt = await stdio.getPrompt({ name: 'design_and_ship', arguments: { task, mode: 'replicate' } });
  assert.deepEqual(stdioPrompt, prompt);
  const stdioResource = await stdio.readResource({ uri: 'token-studio://workflow' });
  assert.deepEqual(stdioResource, workflowResource);
  assert.deepEqual(await stdio.readResource({ uri: workflow.resources.designQuality }), qualityResource);
  const stdioWorkflow = await stdio.callTool({ name: 'get_workflow', arguments: { mode: 'replicate' } });
  assert.ok(Array.isArray(stdioWorkflow.content) && stdioWorkflow.content[0]?.type === 'text');
  assert.deepEqual(JSON.parse(stdioWorkflow.content[0].text as string), workflow);
  assert.deepEqual(await stdio.getPrompt({ name: 'grill_me', arguments: { task: 'Clarify a one-to-one learning platform.' } }), grillPrompt);
  assert.deepEqual(await stdio.readResource({ uri: 'token-studio://workflow/interview' }), interviewResource);
  const stdioTheme = await stdio.callTool({ name: 'get_theme', arguments: { themeId: 'tweakcn:cyberpunk' } });
  assert.equal(stdioTheme.isError, undefined);
  if (Array.isArray(stdioTheme.content) && stdioTheme.content[0]?.type === 'text') assert.deepEqual(JSON.parse(stdioTheme.content[0].text), catalogTheme);
  const viaStdio = await stdio.callTool({ name: 'get_system', arguments: { systemId: id } });
  assert.ok(!viaStdio.isError);
  const themeRevisionBeforeTasks = (await state()).revision;
  const post = (path: string, body: unknown, method = 'POST') => fetch(base + path, { method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  const taskContent = { title: 'Chốt quy tắc đổi lịch', goal: 'Làm rõ quy tắc trước code.', project: 'English', mode: 'grill-me', acceptanceCriteria: ['Có quy tắc và ngoại lệ'], artifacts: [{ id: 'spec', kind: 'spec', label: 'Đặc tả', path: '.token-studio/tasks/demo/SPEC.md' }] };
  const taskResponse = await post('/api/tasks', { task: taskContent }); assert.equal(taskResponse.status, 201); const taskRecord = await taskResponse.json();
  const fromStdio = await stdio.callTool({ name: 'get_task', arguments: { taskId: taskRecord.id } });
  assert.ok(Array.isArray(fromStdio.content) && fromStdio.content[0]?.type === 'text'); assert.deepEqual(JSON.parse(fromStdio.content[0].text), taskRecord);
  assert.equal(JSON.parse((await call('validate_task', { taskId: taskRecord.id })).data).valid, true);
  assert.equal((await client.readResource({ uri: 'token-studio://tasks/schema' })).contents[0].mimeType, 'application/json');
  const completed = JSON.parse((await call('complete_task', { taskId: taskRecord.id, expectedRevision: 0 })).data); assert.equal(completed.status, 'completed');
  assert.equal((await post(`/api/tasks/${taskRecord.id}`, { task: taskContent, expectedRevision: 0 }, 'PATCH')).status, 409);
  const reopened = await (await post(`/api/tasks/${taskRecord.id}`, { task: { ...taskContent, artifacts: [] }, expectedRevision: completed.revision }, 'PATCH')).json();
  assert.equal(reopened.status, 'in-progress');
  assert.equal((await post(`/api/tasks/${taskRecord.id}/complete`, { expectedRevision: reopened.revision })).status, 422);
  assert.equal((await call('complete_task', { taskId: taskRecord.id, expectedRevision: reopened.revision })).error, true);
  assert.equal((await state()).revision, themeRevisionBeforeTasks);
  assert.ok(workflow.taskGuide.includes('complete_task'));
  assert.deepEqual(await stdio.readResource({ uri: workflow.resources.tasks }), await client.readResource({ uri: workflow.resources.tasks }));
});
